"""Browser-bound, server-only ProjectAgain OAuth broker adapter (v0.25).

Native Streamlit OIDC is used *only* to establish a durable, authenticated
browser LOGIN identity: the signed ID token's random nonce is stable across
Streamlit WebSocket reloads. Broker tokens/proofs are sealed in PostgreSQL.
The broker alone holds the OAuth refresh token. No credentials reach the UI.

Production refuses to operate without PostgreSQL, an authenticated native
OIDC browser session, a separate Fernet key, and correctly matching HTTPS URLs.
"""
from __future__ import annotations

import hashlib
import hmac
import secrets
import time
import uuid
from datetime import datetime
from urllib.parse import urlsplit

import requests
from functools import wraps
from cryptography.fernet import Fernet, InvalidToken

from core.oidc_session import LoginState, _trusted_origin, _fetch_identity


BROKER_ENDPOINT = '/api/v1/oauth/broker/'
BROKER_SCOPE = 'openid profile email listing:read buyer_profile:read offer:read'
VALID_SCOPES = {'openid','profile','email','listing:read','buyer_profile:read','offer:read','offer:draft'}
_CALLBACK_KEYS = ('pa_broker_ticket','pa_broker_state','pa_broker_error')


class BrokerError(Exception):
    """A redacted, UI-safe failure without credentials or internal responses."""
    def __init__(self, code, message):
        super().__init__(message)
        self.code = code


class BrokerReauth(BrokerError):
    pass


def _browser_identity(user, expected_issuer, secret_key):
    """Return (session binding, UUID) from an OIDC-authenticated browser cookie.

    `nonce` is generated by Streamlit for EACH native login flow and is included
    in the verified ID token. Unlike the user UUID, this differs on new login.
    The native OIDC ID exp may be past 15 minutes: it supplies a browser cookie
    binding only, never API authorization. Broker verifies current auth each use.
    """
    try:
        if not user.is_logged_in:
            raise ValueError
        claims = user.to_dict()
        uid = str(uuid.UUID(str(claims.get('sub') or '')))
        nonce = claims.get('nonce')
        issuer = str(claims.get('iss') or '').rstrip('/')
        if issuer != _trusted_origin(expected_issuer) or not isinstance(nonce, str) or len(nonce) < 16:
            raise ValueError
        # Binding is a digest; never write the original signed identity token.
        key = hashlib.sha256(b'projectagain-binding-hmac-v1' + secret_key.encode('ascii')).digest()
        raw = 'projectagain-browser-v1\0' + issuer + '\0' + uid + '\0' + nonce
        binding = hmac.new(key, raw.encode('utf-8'), hashlib.sha256).hexdigest()
        return binding, uid
    except (ValueError, AttributeError, TypeError, KeyError, InvalidToken):
        raise BrokerReauth('browser_identity_missing', 'ProjectAgain 계정으로 다시 로그인해 주세요.') from None


def _iso_expiry(value):
    if not isinstance(value, str):
        raise BrokerError('invalid_response', '플랫폼 인증 응답을 확인하지 못했어요.')
    try:
        v = datetime.fromisoformat(value.replace('Z','+00:00'))
        if v.tzinfo is None:
            raise ValueError
        epoch = v.timestamp()
        if not time.time() < epoch < time.time() + 31 * 86400:
            raise ValueError
        return epoch
    except (TypeError, ValueError, OverflowError):
        raise BrokerError('invalid_response', '플랫폼 연결 만료 정보를 확인하지 못했어요.') from None


def _scopes(value):
    if not isinstance(value, str):
        raise BrokerError('invalid_scope','플랫폼 권한 정보를 확인할 수 없어요.')
    scopes = set(value.split())
    if not {'openid','listing:read'}.issubset(scopes) or not scopes <= VALID_SCOPES:
        raise BrokerError('invalid_scope','플랫폼에서 허용되지 않은 권한을 반환했어요.')
    return tuple(sorted(scopes))


class BrokerStore:
    """Encrypted server-side state; PostgreSQL mandatory in production.

    sqlite-only injection is used by unit tests, never for public deployment.
    """
    DDL = (
        '''CREATE TABLE IF NOT EXISTS agent_broker_pending (
            state_hash TEXT PRIMARY KEY, binding_hash TEXT NOT NULL, expected_sub TEXT NOT NULL,
            proof_cipher TEXT NOT NULL, expires_at DOUBLE PRECISION NOT NULL, consumed INTEGER NOT NULL DEFAULT 0
        )''',
        '''CREATE TABLE IF NOT EXISTS agent_broker_sessions (
            binding_hash TEXT PRIMARY KEY, sub TEXT NOT NULL, scope TEXT NOT NULL,
            broker_cipher TEXT NOT NULL, proof_cipher TEXT NOT NULL,
            expires_at DOUBLE PRECISION NOT NULL
        )''',
    )

    def __init__(self, database_url, encryption_key, connection_factory=None):
        self.database_url = database_url
        self.fernet = Fernet(encryption_key.encode('ascii'))
        self.connection_factory = connection_factory
        if connection_factory is None and not (database_url or '').startswith(('postgresql://','postgres://')):
            raise BrokerError('database_required','로그인 저장소에 외부 PostgreSQL 연결이 필요해요.')

    def _db(self):
        if self.connection_factory:
            return self.connection_factory()
        try:
            import psycopg
            return psycopg.connect(self.database_url, connect_timeout=5, sslmode='require')
        except Exception:
            raise BrokerError('storage_unavailable','로그인 저장소 연결에 실패했어요.') from None

    def _sql(self, query):
        return query if self.connection_factory else query.replace('?', '%s')

    def _execute(self, conn, query, args=()):
        return conn.execute(self._sql(query), args)

    def _init(self, conn):
        for ddl in self.DDL:
            conn.execute(ddl)

    @staticmethod
    def _hash(value):
        return hashlib.sha256(value.encode('utf-8')).hexdigest()

    def seal(self, plaintext):
        return self.fernet.encrypt(plaintext.encode('utf-8')).decode('ascii')

    def unseal(self, cipher):
        try:
            return self.fernet.decrypt(cipher.encode('ascii')).decode('utf-8')
        except (InvalidToken, ValueError, AttributeError):
            raise BrokerReauth('credential_unavailable', '로그인 연결 정보를 읽을 수 없어요. 다시 연결해 주세요.') from None

    def pending_put(self, state, browser_binding, sub, proof, ttl=300):
        with self._db() as conn:
            self._init(conn)
            self._execute(conn, '''INSERT INTO agent_broker_pending
                (state_hash,binding_hash,expected_sub,proof_cipher,expires_at,consumed)
                VALUES(?,?,?,?,?,0)''',
                (self._hash(state),browser_binding,sub,self.seal(proof),time.time()+ttl))
            self._execute(conn, 'DELETE FROM agent_broker_pending WHERE expires_at < ?', (time.time()-300,))
            conn.commit()

    def pending_get(self, state, binding, uid, *, lock=False):
        with self._db() as conn:
            self._init(conn)
            sql='''SELECT binding_hash,expected_sub,proof_cipher,expires_at,consumed FROM
                agent_broker_pending WHERE state_hash=?'''
            if lock and not self.connection_factory:
                sql += ' FOR UPDATE'
            row=self._execute(conn,sql,(self._hash(state),)).fetchone()
        if not row or row[0]!=binding or row[1]!=uid or row[4] or row[3]<time.time():
            raise BrokerReauth('invalid_state','로그인 요청이 만료되었거나 다른 브라우저에서 시작됐어요. 다시 연결해 주세요.')
        return self.unseal(row[2])

    def finish(self, state, binding, uid, ticket, exchange):
        """Atomically consume local pending state, commit broker credential.
        
        Remote ticket exchange is one-time; DB failures fail closed. Postgres
        row lock prevents two callbacks concurrently exchanging the same ticket.
        """
        with self._db() as conn:
            self._init(conn)
            query='''SELECT binding_hash,expected_sub,proof_cipher,expires_at,consumed FROM
                agent_broker_pending WHERE state_hash=?'''
            if not self.connection_factory:
                query+=' FOR UPDATE'
            row=self._execute(conn,query,(self._hash(state),)).fetchone()
            if not row or row[0]!=binding or row[1]!=uid or row[4] or row[3]<time.time():
                raise BrokerReauth('invalid_state','로그인 요청이 만료되었거나 다른 브라우저에서 시작됐어요.')
            proof=self.unseal(row[2])
            response=exchange(ticket,state,proof)
            if str(uuid.UUID(str(response.get('sub') or ''))) != uid:
                raise BrokerError('account_mismatch','로그인 계정이 일치하지 않아요.')
            scope=' '.join(_scopes(response.get('scope')))
            credential=response.get('broker_session')
            if not isinstance(credential,str) or len(credential)<20:
                raise BrokerError('invalid_response','로그인 연결 정보를 확인할 수 없어요.')
            expiry=_iso_expiry(response.get('expires_at'))
            self._execute(conn, '''INSERT INTO agent_broker_sessions
                (binding_hash,sub,scope,broker_cipher,proof_cipher,expires_at)
                VALUES(?,?,?,?,?,?) ON CONFLICT(binding_hash) DO UPDATE SET
                sub=excluded.sub,scope=excluded.scope,broker_cipher=excluded.broker_cipher,
                proof_cipher=excluded.proof_cipher,expires_at=excluded.expires_at''',
                (binding,uid,scope,self.seal(credential),self.seal(proof),expiry))
            self._execute(conn,'UPDATE agent_broker_pending SET consumed=1 WHERE state_hash=?',(self._hash(state),))
            conn.commit()
            return scope

    def session(self, binding, uid):
        with self._db() as conn:
            self._init(conn)
            row=self._execute(conn,'''SELECT sub,scope,broker_cipher,proof_cipher,expires_at
                FROM agent_broker_sessions WHERE binding_hash=?''',(binding,)).fetchone()
        if not row or row[0]!=uid:
            return None
        if row[4]<=time.time():
            self.clear(binding)
            return None
        return {'sub':uid,'scope':row[1],'broker_session':self.unseal(row[2]),
                'session_proof':self.unseal(row[3])}

    def clear(self,binding):
        with self._db() as conn:
            self._init(conn)
            self._execute(conn,'DELETE FROM agent_broker_sessions WHERE binding_hash=?',(binding,))
            self._execute(conn,'DELETE FROM agent_broker_pending WHERE binding_hash=?',(binding,))
            conn.commit()


def _safe_storage_operation(method):
    @wraps(method)
    def guarded(self,*args,**kwargs):
        try:
            return method(self,*args,**kwargs)
        except BrokerError:
            raise
        except Exception:
            # Database failures are never rendered with connection strings.
            raise BrokerError('storage_unavailable','로그인 저장소에 일시적인 문제가 있어요.') from None
    return guarded

for _store_method in ('pending_put','pending_get','finish','session','clear'):
    setattr(BrokerStore,_store_method,_safe_storage_operation(getattr(BrokerStore,_store_method)))


class BrokerClient:
    def __init__(self, origin, client_id, client_secret, *, sender=None):
        self.origin = _trusted_origin(origin)
        if not self.origin or not client_id or len(client_secret)<32:
            raise BrokerError('not_configured','ProjectAgain 연결 설정을 확인해 주세요.')
        self.client_id=client_id
        self.client_secret=client_secret
        self.sender=sender

    def post(self,path,body,session=None):
        if path not in ('intents','tickets/exchange','access','logout'):
            raise BrokerError('invalid_path','허용되지 않은 인증 요청입니다.')
        url=self.origin+BROKER_ENDPOINT+path
        try:
            if self.sender:
                status,data=self.sender(path,body,session)
            else:
                headers={'Content-Type':'application/json','Accept':'application/json'}
                if session:
                    headers['x-broker-session']=session
                r=requests.post(url,json=body,headers=headers,
                    auth=(self.client_id,self.client_secret),timeout=(3,9),allow_redirects=False)
                status=r.status_code
                data=r.json() if status!=204 else {}
            if status!=200:
                code = data.get('error') if isinstance(data,dict) else None
                if isinstance(code,dict):
                    code=code.get('message') or code.get('code')
                if code=='reauth_required' or code=='invalid_ticket':
                    raise BrokerReauth('reauth_required','연결이 만료되었어요. ProjectAgain 계정을 다시 연결해 주세요.')
                if status==503:
                    raise BrokerError('temporarily_unavailable','인증 서버에 일시적인 문제가 있어요. 잠시 후 다시 시도해 주세요.')
                raise BrokerError('broker_denied','ProjectAgain 연결 요청을 처리하지 못했어요.')
            if not isinstance(data,dict):
                raise BrokerError('invalid_response','플랫폼 인증 응답이 올바르지 않아요.')
            return data
        except (requests.RequestException,ValueError):
            raise BrokerError('temporarily_unavailable','플랫폼 인증 서버에 연결하지 못했어요.') from None

    def begin(self,state,proof,scope=BROKER_SCOPE):
        result=self.post('intents',{'client_state':state,'session_binding_hash':hashlib.sha256(proof.encode()).hexdigest(),
                                   'scope':scope})
        url=result.get('authorization_url')
        parsed=urlsplit(url if isinstance(url,str) else '')
        if parsed.scheme!='https' or parsed.netloc!=urlsplit(self.origin).netloc or parsed.path!='/api/v1/oauth/authorize':
            raise BrokerError('invalid_redirect','로그인 주소를 확인할 수 없어요.')
        return url

    def exchange(self,ticket,state,proof):
        return self.post('tickets/exchange',{'ticket':ticket,'client_state':state,'session_proof':proof})

    def access(self,record,*,force=False,observed_token=''):
        payload={'session_proof':record['session_proof']}
        if force:
            if not observed_token:
                raise BrokerError('missing_observed','실패한 요청 정보를 확인할 수 없어요.')
            payload.update(force_refresh=True,observed_access_token_hash=hashlib.sha256(observed_token.encode()).hexdigest())
        result=self.post('access',payload,record['broker_session'])
        if result.get('sub')!=record['sub']:
            raise BrokerError('account_mismatch','인증된 계정 정보가 변경됐어요.')
        if not set(_scopes(result.get('scope'))) <= set(record['scope'].split()):
            raise BrokerError('scope_mismatch','허용된 권한 범위가 변경됐어요.')
        token=result.get('access_token')
        if not isinstance(token,str) or len(token)<20 or result.get('token_type')!='Bearer':
            raise BrokerError('invalid_response','API 인증 정보를 확인할 수 없어요.')
        return token,tuple(_scopes(result['scope']))

    def logout(self,record):
        return self.post('logout',{'session_proof':record['session_proof']},record['broker_session'])


def new_intent(store,client,binding,uid,scope=BROKER_SCOPE):
    state=secrets.token_urlsafe(32)
    proof=secrets.token_urlsafe(48)
    store.pending_put(state,binding,uid,proof)
    return client.begin(state,proof,scope)


def resolve_broker(store,client,binding,uid,issuer,*, fetch=None):
    record=store.session(binding,uid)
    if not record:
        return LoginState('guest'),None
    token,scopes=client.access(record)
    origin=_trusted_origin(issuer)
    if not origin or origin!=client.origin:
        raise BrokerError('issuer_mismatch','플랫폼 주소가 일치하지 않습니다.')
    fetcher=fetch or _fetch_identity
    result,profile=fetcher(origin+'/api/v1/oauth/userinfo',token)
    if result!='ok' or not isinstance(profile,dict) or profile.get('sub')!=uid:
        raise BrokerError('invalid_identity','플랫폼 계정을 확인하지 못했어요.')
    result,me=fetcher(origin+'/api/v1/auth/me',token)
    if result!='ok' or not isinstance(me,dict) or me.get('id')!=uid:
        raise BrokerError('invalid_identity','플랫폼 계정 권한을 확인하지 못했어요.')
    owner=hashlib.sha256((issuer.rstrip('/')+'::'+uid).encode()).hexdigest()
    return (LoginState('connected',user_id=uid,access_token=token,
                       owner_key=owner,ai_identity='platform:'+owner,scopes=scopes),record)
